// Package i18n is the Go-owned operator UI message catalog. It supports
// exactly English (en) and Japanese (ja).
//
// A message ID is its English source text, so English needs no table and is
// the deterministic fallback: a message without a Japanese entry renders in
// English. Only operator-facing copy is looked up here; API fields, evidence,
// identifiers, paths, logs and model output never pass through the catalog.
package i18n

import (
	"fmt"
	"os"
	"strings"
)

// Locale is a supported operator UI locale.
type Locale string

const (
	English  Locale = "en"
	Japanese Locale = "ja"
)

// Supported lists the selectable locales in display order.
var Supported = []Locale{English, Japanese}

// Name is the locale's own name, shown untranslated in the selector.
func (l Locale) Name() string {
	if l == Japanese {
		return "日本語"
	}
	return "English"
}

// Valid reports whether s names a supported locale exactly ("en" or "ja").
func Valid(s string) bool {
	for _, l := range Supported {
		if string(l) == s {
			return true
		}
	}
	return false
}

// Resolve picks the locale: an explicit saved selection wins; an unset (or
// unsupported) one resolves from the host locale tags in order, matching
// their language subtag ("ja-JP", "ja_JP.UTF-8"); anything else is English.
func Resolve(saved string, host ...string) Locale {
	if Valid(saved) {
		return Locale(saved)
	}
	for _, h := range host {
		lang := strings.ToLower(h)
		if i := strings.IndexAny(lang, "-_.@"); i >= 0 {
			lang = lang[:i]
		}
		if Valid(lang) {
			return Locale(lang)
		}
	}
	return English
}

// HostLocales are the host's locale tags from the POSIX locale environment,
// in precedence order. Unset variables are skipped.
func HostLocales() []string {
	var out []string
	for _, k := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		if v := os.Getenv(k); v != "" && v != "C" && v != "POSIX" {
			out = append(out, v)
		}
	}
	return out
}

// T renders message msg in l, formatting args (fmt verbs) when given. A
// missing Japanese entry falls back to the English source text.
func (l Locale) T(msg string, args ...any) string {
	text := msg
	if l == Japanese {
		if v, ok := ja[msg]; ok {
			text = v
		}
	}
	if len(args) > 0 {
		return fmt.Sprintf(text, args...)
	}
	return text
}

// Has reports whether l has its own entry for msg (English always does).
func (l Locale) Has(msg string) bool {
	if l == English {
		return true
	}
	_, ok := ja[msg]
	return ok
}

// Table renders msgs in l, keyed by message ID, for a page script that
// shows operator copy computed in the browser.
func (l Locale) Table(msgs []string) map[string]string {
	m := make(map[string]string, len(msgs))
	for _, k := range msgs {
		m[k] = l.T(k)
	}
	return m
}

